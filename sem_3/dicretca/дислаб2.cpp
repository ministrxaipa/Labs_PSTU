#include <iostream>
#include <fstream>    // для чтения файлов (ifstream)
#include <string>
#include <windows.h>  // для русского в консоли
//О СВОЙСТВАХ
//Рефлексивность: каждый элемент связан сам с собой (на диагонали одни 1).
//Антирефлексивность: ни один элемент не связан сам с собой (на диагонали одни 0).
//Симметричность: если A связан с B, то и B связан с A (матрица симметрична относительно диагонали).
//Антисимметричность: если A связан с B (и A ≠ B), то B не связан с A. Нельзя, чтобы m[i][j]=1 и m[j][i]=1 одновременно.
//Транзитивность: если A связан с B и B связан с C, то A связан с C.
//Связность (полнота): для любых двух разных элементов хотя бы один связан с другим (хотя бы одна 1 в паре m[i][j] и m[j][i]).
//ТИПЫ
//Эквивалентность = рефлексивность + симметричность + транзитивность.
//Порядок = антисимметричность + транзитивность.
//Строгий порядок = антирефлексивность + порядок.
//Полный (линейный) порядок = связность + порядок.
//Частичный/нестрогий = порядок, если не полный.

using namespace std;

// ============================================================
// РАЗМЕР МАТРИЦЫ — 6×6 (по заданию)
// ============================================================
const int N = 6;

// ============================================================
// ЗАГРУЗКА МАТРИЦЫ ИЗ ФАЙЛА
// Принимает имя файла и матрицу (по ссылке, чтобы заполнить)
// Возвращает true если удалось, false если нет
// ============================================================
bool zagruzitMatricu(string imyaFaila, int matr[N][N]) {
    ifstream f(imyaFaila);  // открываем файл на чтение
    if (!f.is_open()) {     // если не открылся — сообщаем
        cout << "Не удалось открыть файл: " << imyaFaila << "\n";
        return false;
    }

    // Читаем N*N чисел
    for (int i = 0; i < N; i++) {       //по строкам
        for (int j = 0; j < N; j++) {   //по столбцам
            if (!(f >> matr[i][j])) {   // если не удалось прочитать — ошибка
                cout << "Ошибка чтения в позиции " << i << "," << j << "\n";
                f.close();
                return false;
            }
        }
    }
    f.close();
    return true;
}

// ============================================================
// БЕЗОПАСНЫЙ ВВОД ЧИСЛА
// Если ввести букву — попросит ввести заново (защита от зацикливания)
// ============================================================
int vvod() {
    int x;
    while (!(cin >> x)) {       //пока cin не может прочитать int
        cin.clear();            //сбрасываем флаг ошибки
        cin.ignore(10000, '\n');//выкидываем мусор из буфера
        cout << "Нужно число, попробуй ещё: ";
    }
    return x;
}

// ============================================================
// ВЫВОД МАТРИЦЫ НА ЭКРАН
// ============================================================
void pokazatMatricu(int matr[N][N]) {
    for (int i = 0; i < N; i++) {       //по каждой строке
        for (int j = 0; j < N; j++) {   //по каждому столбцу
            cout << matr[i][j] << " ";  //печатаем число+пробел
        }
        cout << "\n";                   //в конце строки перенос
    }
}

// ============================================================
// РЕФЛЕКСИВНОСТЬ
// Все элементы на главной диагонали равны 1
// ============================================================
bool checkRefleksivnost(int matr[N][N]) {
    for (int i = 0; i < N; i++) {           //проходим по диагонали
        if (matr[i][i] != 1) return false;  // нашли 0 на диагонали (не рефлексивно)
    }
    return true;    //все 1-рефлексивно
}

// ============================================================
// АНТИРЕФЛЕКСИВНОСТЬ
// Все элементы на главной диагонали равны 0
// ============================================================
bool checkAntiRefleksivnost(int matr[N][N]) {
    for (int i = 0; i < N; i++) {
        if (matr[i][i] != 0) return false;  // нашли 1 на диагонали (не антирефлексивно)
    }
    return true;
}

// ============================================================
// СИММЕТРИЧНОСТЬ
// Для всех i,j: matr[i][j] == matr[j][i]
// ============================================================
bool checkSimmetrichnost(int matr[N][N]) {
    for (int i = 0; i < N; i++) {
        for (int j = 0; j < N; j++) {
            if (matr[i][j] != matr[j][i]) return false;  // пара не совпала
        }
    }
    return true;
}

// ============================================================
// АНТИСИММЕТРИЧНОСТЬ: нельзя, чтобы m[i][j]=1 и m[j][i]=1 одновременно
// (кроме i==j — на диагонали ограничений нет)
// ============================================================
bool checkAntiSimmetrichnost(int matr[N][N]) {
    for (int i = 0; i < N; i++) {
        for (int j = 0; j < N; j++) {
            if (i != j) {  // только для разных элементов
                if (matr[i][j] == 1 && matr[j][i] == 1) return false;  // нашли обе 1-плохо
            }
        }
    }
    return true;
}

// ============================================================
// ТРАНЗИТИВНОСТЬ
// Если matr[i][j]=1 и matr[j][k]=1, то matr[i][k] должно быть 1
// ============================================================
bool checkTranzitivnost(int matr[N][N]) {
    for (int i = 0; i < N; i++) {
        for (int j = 0; j < N; j++) {
            if (matr[i][j] == 1) {              // если i связан с j
                for (int k = 0; k < N; k++) {
                    if (matr[j][k] == 1) {      // и j связан с k
                        if (matr[i][k] != 1) return false;  // а i с k-нет, нарушение транзитивности
                    }
                }
            }
        }
    }
    return true;
}

// ============================================================
// СВЯЗНОСТЬ (ПОЛНОТА)
// Для всех i≠j хотя бы одно из matr[i][j], matr[j][i] равно 1
// ============================================================
bool checkSvyaznost(int matr[N][N]) {
    for (int i = 0; i < N; i++) {
        for (int j = 0; j < N; j++) {
            if (i != j) {  // только для разных элементов
                if (matr[i][j] != 1 && matr[j][i] != 1) return false;  // оба 0-плохо
            }
        }
    }
    return true;
}

// ============================================================
// ОПРЕДЕЛЕНИЕ ТИПА ОТНОШЕНИЯ
// Принимает все флаги свойств, возвращает строку с названием типа
// ============================================================
string opredelitTip(bool refl, bool antiRefl, bool simm, bool antiSimm,
                    bool tranz, bool svyaz) {
    // Эквивалентность = рефлексивность + симметричность + транзитивность
    if (refl && simm && tranz) return "Эквивалентность";

    // Порядок = антисимметричность + транзитивность
    bool poryadok = antiSimm && tranz;

    if (poryadok) {
        // Строгий порядок = антирефлексивность + порядок
        if (antiRefl) return "Строгий порядок";
        // Полный (линейный) порядок = связность + порядок
        if (svyaz) return "Полный (линейный) порядок";
        // Нестрогий частичный порядок = рефлексивность + порядок
        if (refl) return "Нестрогий частичный порядок";
        // Просто порядок без уточнений
        return "Частичный порядок";
    }

    // Ничего не подошло
    return "Отношение общего вида (не является ни эквивалентностью, ни порядком)";
}

