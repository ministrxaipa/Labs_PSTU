// ГЛАВНАЯ ФУНКЦИЯ
// ============================================================
int main() {
    SetConsoleOutputCP(CP_UTF8); //русский в консоле(вывод)
    SetConsoleCP(CP_UTF8);       //русскиц в еонсоле(ввод)

    // Бесконечный цикл: крутимся, пока пользователь не введёт 0
    while (true) {
        cout << "\n===== ОПРЕДЕЛЕНИЕ СВОЙСТВ ОТНОШЕНИЙ =====\n";
        cout << "Введи номер файла (1..8) или 0 для выхода: ";

        int nomer = vvod();  // безопасный ввод числа (буквы не сломают программу)

        if (nomer == 0) {
            cout << "Выход из программы.\n";
            break;  // выходим из бесконечного цикла
        }

        // Проверка: номер должен быть от 1 до 8
        if (nomer < 1 || nomer > 8) {
            cout << "Ошибка: номер должен быть от 1 до 8. Попробуй ещё.\n";
            continue;  // возвращаемся в начало while
        }

        // Собираем имя файла: 1 -> "m1.txt"
        string imyaFaila = "m" + to_string(nomer) + ".txt";
        cout << "Открываю файл: " << imyaFaila << "\n";

        // Пытаемся загрузить. Если не получилось — сообщение и повтор
        int matr[N][N];
        if (!zagruzitMatricu(imyaFaila, matr)) {
            cout << "Попробуй другой номер.\n";
            continue;  // возвращаемся в начало while
        }

        // Матрица загружена — показываем её
        cout << "\nЗагруженная матрица:\n";
        pokazatMatricu(matr);

        // Проверяем все свойства
        bool refl     = checkRefleksivnost(matr);
        bool antiRefl = checkAntiRefleksivnost(matr);
        bool simm     = checkSimmetrichnost(matr);
        bool antiSimm = checkAntiSimmetrichnost(matr);
        bool tranz    = checkTranzitivnost(matr);
        bool svyaz    = checkSvyaznost(matr);

        // Выводим отчёт
        cout << "\n===== СВОЙСТВА ОТНОШЕНИЯ =====\n";
        cout << "Рефлексивность:        " << (refl     ? "ДА" : "НЕТ") << "\n";
        cout << "Антирефлексивность:    " << (antiRefl ? "ДА" : "НЕТ") << "\n";
        cout << "Симметричность:        " << (simm     ? "ДА" : "НЕТ") << "\n";
        cout << "Антисимметричность:    " << (antiSimm ? "ДА" : "НЕТ") << "\n";
        cout << "Транзитивность:        " << (tranz    ? "ДА" : "НЕТ") << "\n";
        cout << "Связность (полнота):   " << (svyaz    ? "ДА" : "НЕТ") << "\n";

        cout << "\n===== ТИП ОТНОШЕНИЯ =====\n";
        cout << opredelitTip(refl, antiRefl, simm, antiSimm, tranz, svyaz) << "\n";

        // После отчёта цикл вернётся в начало и снова спросит номер
    }

    return 0;
}